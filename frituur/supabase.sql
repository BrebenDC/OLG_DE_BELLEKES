-- 3. Historie van alle inwisselingen
create table if not exists public.frituur_log (
  id           bigint generated by default as identity primary key,
  at           timestamptz not null default now(),
  number       int,
  action       text not null,
  result       text not null,
  amount_cents int,
  by_email     text
);

-- 4. Beveiliging: niemand mag de tabellen rechtstreeks lezen of wijzigen.
--    Alles loopt via de functies hieronder, die eerst controleren of je beheerder bent.
alter table public.frituur_cards    enable row level security;
alter table public.frituur_log enable row level security;

-- Instelling: mag iedereen die zelf een account maakt (e-mail of Google) meteen scannen?
--   true  = ja, elk ingelogd account mag scannen en afschrijven
--   false = alleen e-mailadressen uit de tabel 'admins'
-- Kaart controleren (zonder iets af te trekken)
create or replace function public.verify_card2(p_token text) returns json
language plpgsql security definer set search_path = public as $$
declare c frituur_cards;
begin
  perform require_admin();
  select * into c from frituur_cards where token = p_token;
  if not found then return json_build_object('result', 'invalid'); end if;
  return json_build_object(
    'result', case when c.balance_cents <= 0 then 'already_used' else 'valid' end,
    'number', c.number, 'created_at', c.created_at,
    'redeemed_at', c.redeemed_at, 'balance_cents', greatest(c.balance_cents, 0));
end $$;

-- Bedrag aftrekken (atomair: twee telefoons tegelijk kunnen nooit dubbel aftrekken)
create or replace function public.redeem_card2(p_token text, p_amount int) returns json
language plpgsql security definer set search_path = public as $$
declare c frituur_cards; who text := auth.jwt() ->> 'email';
begin
  perform require_admin();
  if p_amount is null or p_amount < 1 or p_amount > 1500 then
    return json_build_object('result', 'invalid');
  end if;
  select * into c from frituur_cards where token = p_token for update;
  if not found then return json_build_object('result', 'invalid'); end if;

  if c.balance_cents <= 0 then
    insert into frituur_log(number, action, result, by_email) values (c.number, 'redeem', 'already_used', who);
    return json_build_object('result', 'already_used', 'number', c.number, 'created_at', c.created_at,
                             'redeemed_at', c.redeemed_at, 'balance_cents', 0);
  end if;

  if p_amount > c.balance_cents then
    insert into frituur_log(number, action, result, amount_cents, by_email) values (c.number, 'redeem', 'insufficient', p_amount, who);
    return json_build_object('result', 'insufficient', 'number', c.number, 'created_at', c.created_at,
                             'redeemed_at', c.redeemed_at, 'balance_cents', c.balance_cents);
  end if;

  update frituur_cards set balance_cents = balance_cents - p_amount,
                   redeemed_at = case when balance_cents - p_amount = 0 then now() else redeemed_at end
   where number = c.number
   returning * into c;
  insert into frituur_log(number, action, result, amount_cents, by_email) values (c.number, 'redeem', 'redeemed', p_amount, who);
  return json_build_object('result', 'redeemed', 'number', c.number, 'created_at', c.created_at,
                           'redeemed_at', c.redeemed_at, 'balance_cents', c.balance_cents);
end $$;

-- Kaartenlijst (zonder geheime tokens)
create or replace function public.list_cards2()
returns table(number int, balance_cents int, created_at timestamptz, redeemed_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  perform require_admin();
  return query select c.number, c.balance_cents, c.created_at, c.redeemed_at from frituur_cards c order by c.number;
end $$;

-- Token van één kaart (om de QR-code te tonen)
create or replace function public.card_token2(p_number int) returns text
language plpgsql stable security definer set search_path = public as $$
declare t text;
begin
  perform require_admin();
  select token into t from frituur_cards where number = p_number;
  return t;
end $$;

-- Historie
create or replace function public.card_history2()
returns table(at timestamptz, number int, action text, result text, amount_cents int, by_email text)
language plpgsql stable security definer set search_path = public as $$
begin
  perform require_admin();
  return query select l.at, l.number, l.action, l.result, l.amount_cents, l.by_email
                 from frituur_log l order by l.at desc limit 300;
end $$;

-- Alleen ingelogde gebruikers mogen de functies aanroepen
revoke all on function public.verify_card2(text), public.redeem_card2(text, int), public.list_cards2(),
                       public.card_token2(int), public.card_history2() from public, anon;
grant execute on function public.verify_card2(text), public.redeem_card2(text, int),
                          public.list_cards2(), public.card_token2(int), public.card_history2() to authenticated;
